"""Install the built wheel in a fresh environment and exercise both CLI formats."""

import json
import os
import subprocess
import sys
import tempfile
import venv
from pathlib import Path


def main() -> None:
    repository = Path(__file__).resolve().parents[1]
    distribution = Path(sys.argv[1] if len(sys.argv) > 1 else "dist").resolve()
    wheels = list(distribution.glob("repolens_inspector-*.whl"))
    if len(wheels) != 1:
        raise SystemExit("Expected exactly one RepoLens wheel")
    with tempfile.TemporaryDirectory(prefix="repolens-wheel-") as temporary:
        root = Path(temporary)
        venv.create(root / "venv", with_pip=True)
        python = root / "venv" / ("Scripts/python.exe" if os.name == "nt" else "bin/python")
        environment = {key: value for key, value in os.environ.items() if key != "PYTHONPATH"}
        environment["PYTHONIOENCODING"] = "utf-8"

        def run(*args: str) -> str:
            return subprocess.run(
                [str(python), *args],
                cwd=root,
                env=environment,
                check=True,
                capture_output=True,
                text=True,
                encoding="utf-8",
            ).stdout

        try:
            run("-m", "pip", "install", str(wheels[0]))
            version = run("-m", "repolens", "version").strip()
            assert wheels[0].name.startswith(f"repolens_inspector-{version}-")
            target = str(repository / "examples" / "demo_repo")
            raw = run("-m", "repolens", "analyze", target, "--local", "--format", "json")
            report = json.loads(raw)
            assert report["inventory_complete"] and report["content_complete"]
            assert len(report["modules"]) == 3 and len(report["import_edges"]) == 1
            text = run("-m", "repolens", "analyze", target, "--local")
            assert "```mermaid" in text and f"Generated by RepoLens {version}" in text

            target = str(repository / "examples" / "cpp_demo")
            raw = run("-m", "repolens", "analyze", target, "--local", "--format", "json")
            report = json.loads(raw)
            assert report["schema_version"] == "1.3" and report["content_complete"]
            header, main_file = report["cpp_files"]
            assert header["symbols"][-1]["name"] == "demo::Greeter::message"
            assert main_file["includes"][0]["target"] == "include/greeter.hpp"
            assert report["entry_points"][0]["line"] == 4
            text = run("-m", "repolens", "analyze", target, "--local")
            assert "## C++ 源文件与头文件" in text and "demo::Greeter::message" in text
            target = str(repository / "examples" / "ts_demo")
            raw = run("-m", "repolens", "analyze", target, "--local", "--format", "json")
            report_path = root / "typescript.json"
            report_path.write_text(raw, encoding="utf-8")
            preview = run("-m", "repolens", "explain", str(report_path))
            assert "GreetingView.tsx:3" in preview and "预览费用为 0" in preview
            view, greeting = json.loads(raw)["typescript_files"]
            assert not view["has_parse_errors"] and not greeting["has_parse_errors"]
            assert view["references"][0]["target"] == greeting["path"] == "greeting.ts"
            text = run("-m", "repolens", "analyze", target, "--local")
            assert "## TypeScript 源文件" in text and "GreetingView.tsx:3" in text
        except subprocess.CalledProcessError as error:
            print(error.stdout, file=sys.stderr)
            print(error.stderr, file=sys.stderr)
            raise SystemExit(error.returncode) from None
    print(f"Installed wheel {version}: JSON and Markdown smoke tests passed")


if __name__ == "__main__":
    main()
